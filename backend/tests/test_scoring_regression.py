"""Scoring must be unchanged by the move to remote embeddings.

Golden reports in fixtures/golden_reports.json were generated by the ORIGINAL code on
`main` (with only the embedding step pinned), so these tests prove the 40/40/20 formula,
rounding, X-Ray, job intelligence and suggestion logic are byte-for-byte unchanged.
"""

import asyncio
import json
import os
import subprocess
import sys
from pathlib import Path

import pytest

from app import analyzer
from app.main import app
from app.schemas import AnalyzeResponse

from conftest import (
    FIXTURES, FakeProvider, golden, hf_ok_response, install_provider, make_pdf,
    read_fixture, run_with_app, analyze_request, vectors_with_cosine,
)

BACKEND_DIR = Path(__file__).resolve().parent.parent
CASES = {
    "strong": ("strong_resume.txt", "strong_jd.txt"),
    "weak": ("weak_resume.txt", "weak_jd.txt"),
    "noskills": ("noskills_resume.txt", "noskills_jd.txt"),
}
GOLDEN = golden()


def _without_keyword_order(report):
    """`important_keywords` is excluded from exact comparison: the original code returned a
    hash-seed-dependent subset/order for tied keywords (fixed separately and tested below)."""
    report = json.loads(json.dumps(report))
    report["job_intelligence"].pop("important_keywords")
    return report


@pytest.mark.parametrize("case", sorted(CASES))
@pytest.mark.parametrize("semantic", ["0.0", "37.4", "62.5", "100.0"])
def test_report_matches_original_implementation_exactly(case, semantic):
    resume, jd = (read_fixture(f) for f in CASES[case])
    actual = analyzer.build_report(resume, jd, float(semantic))
    assert _without_keyword_order(actual) == _without_keyword_order(GOLDEN[case][semantic])


@pytest.mark.parametrize("case", sorted(CASES))
def test_important_keywords_are_valid_and_frequency_ordered(case):
    import re
    resume, jd = (read_fixture(f) for f in CASES[case])
    intel = analyzer.build_report(resume, jd, 50.0)["job_intelligence"]
    keywords = intel["important_keywords"]
    assert len(keywords) <= 10 and set(keywords) <= set(intel["technical_skills"])
    counts = [len(re.findall(re.escape(k), jd, re.IGNORECASE)) for k in keywords]
    assert counts == sorted(counts, reverse=True)
    # ties are alphabetical
    assert all(
        (counts[i], keywords[i]) <= (counts[i], keywords[i + 1]) if counts[i] == counts[i + 1] else True
        for i in range(len(keywords) - 1)
    )


def test_important_keywords_are_identical_across_process_restarts():
    """Regression: output used to depend on PYTHONHASHSEED (different keywords after each restart)."""
    code = (
        "import json; from app import analyzer; "
        f"jd=open({str(FIXTURES / 'strong_jd.txt')!r}).read().strip(); "
        "print(json.dumps(analyzer.extract_important_keywords(jd)))"
    )
    outputs = {
        subprocess.run(
            [sys.executable, "-c", code], cwd=BACKEND_DIR, capture_output=True, text=True, check=True,
            env={**os.environ, "PYTHONHASHSEED": seed},
        ).stdout
        for seed in ("1", "2", "3", "4")
    }
    assert len(outputs) == 1


@pytest.mark.parametrize("case", sorted(CASES))
def test_overall_score_is_40_40_20_blend(case):
    resume, jd = (read_fixture(f) for f in CASES[case])
    semantic = 62.5
    keyword, _, missing = analyzer.compute_keyword_match(resume, jd)
    ats, _ = analyzer.analyze_ats(resume, jd, missing)
    report = analyzer.build_report(resume, jd, semantic)
    assert report["overall_score"] == round(0.4 * semantic + 0.4 * keyword + 0.2 * ats)


@pytest.mark.parametrize(
    "cosine,expected",
    [(1.0, 100.0), (0.625, 62.5), (0.3, 30.0), (0.0, 0.0), (-0.4, 0.0)],  # negative clamps to 0
)
def test_semantic_score_is_clamped_scaled_cosine(cosine, expected):
    client = install_provider(FakeProvider(lambda r: hf_ok_response(cosine)))
    score = asyncio.run(analyzer.compute_semantic_similarity("resume", "jd", client))
    assert score == pytest.approx(expected, abs=0.05)


def test_analysis_is_deterministic_for_same_embeddings():
    resume, jd = (read_fixture(f) for f in CASES["strong"])
    results = []
    for _ in range(3):
        client = install_provider(FakeProvider(lambda r: hf_ok_response(0.5)))
        results.append(asyncio.run(analyzer.run_analysis(resume, jd, client)))
    assert results[0] == results[1] == results[2]


def test_response_schema_is_unchanged_from_original():
    snapshot = json.loads((FIXTURES / "analyze_response_schema.json").read_text())
    assert AnalyzeResponse.model_json_schema() == snapshot


def test_api_response_through_pdf_upload_matches_golden():
    """Full path: PDF upload -> extraction -> (test-controlled) embeddings -> response."""
    resume, jd = (read_fixture(f) for f in CASES["strong"])
    pdf = make_pdf([resume])
    install_provider(FakeProvider(lambda r: hf_ok_response(0.625)))

    response = run_with_app(app, analyze_request(app, pdf, jd))

    assert response.status_code == 200
    body = response.json()
    expected = GOLDEN["strong"]["62.5"]
    assert set(body) == set(AnalyzeResponse.model_fields)  # every existing field, nothing missing
    for field in ("overall_score", "semantic_similarity", "keyword_match", "ats_score",
                  "matched_skills", "missing_skills", "ats_issues"):
        assert body[field] == expected[field], field
    assert {k: v for k, v in body["job_intelligence"].items() if k != "important_keywords"} == \
           {k: v for k, v in expected["job_intelligence"].items() if k != "important_keywords"}
    assert [i["label"] for i in body["resume_xray"]] == [i["label"] for i in expected["resume_xray"]]
